class NonSeparableQuantumWalk:
    """
    Quantum walk on n×m torus with a general 4-state coin.

    The walker moves in four directions: right(R), left(L), up(U), down(D)
    The coin is a 4×4 unitary matrix that mixes these four directions.
    """

    def __init__(self, n, m):
        """
        Initialize walk on n×m torus.

        Parameters:
        - n: number of rows (y-dimension)
        - m: number of columns (x-dimension)
        """
        self.n = n  # rows
        self.m = m  # columns
        self.N = n * m  # number of vertices
        self.dim = 4 * self.N  # total Hilbert space dimension (4 coin states × N positions)

        # Direction indices
        self.R = 0  # right
        self.L = 1  # left
        self.U = 2  # up
        self.D = 3  # down

        # Precompute neighbor indices
        self._build_neighbors()

    def _build_neighbors(self):
        """Precompute neighbor indices for each position."""
        self.right_neighbor = np.zeros(self.N, dtype=int)
        self.left_neighbor = np.zeros(self.N, dtype=int)
        self.up_neighbor = np.zeros(self.N, dtype=int)
        self.down_neighbor = np.zeros(self.N, dtype=int)

        for i in range(self.n):
            for j in range(self.m):
                idx = i * self.m + j

                # Right: (i, j) → (i, j+1)
                self.right_neighbor[idx] = i * self.m + ((j + 1) % self.m)
                # Left: (i, j) → (i, j-1)
                self.left_neighbor[idx] = i * self.m + ((j - 1) % self.m)
                # Up: (i, j) → (i-1, j)
                self.up_neighbor[idx] = ((i - 1) % self.n) * self.m + j
                # Down: (i, j) → (i+1, j)
                self.down_neighbor[idx] = ((i + 1) % self.n) * self.m + j

    def _build_shift_operators(self):
        """Build the conditional shift operators for each direction."""

        # Shift operators for each direction (act on position space)
        self.S_R = np.zeros((self.N, self.N), dtype=complex)
        self.S_L = np.zeros((self.N, self.N), dtype=complex)
        self.S_U = np.zeros((self.N, self.N), dtype=complex)
        self.S_D = np.zeros((self.N, self.N), dtype=complex)

        for pos in range(self.N):
            self.S_R[self.right_neighbor[pos], pos] = 1
            self.S_L[self.left_neighbor[pos], pos] = 1
            self.S_U[self.up_neighbor[pos], pos] = 1
            self.S_D[self.down_neighbor[pos], pos] = 1

    def create_coin_grover(self):
        """Create the Grover diffusion coin (4×4)."""
        # Grover coin: 2/|V| * J - I
        # For 4 directions: G = 2/4 * J - I = 0.5*J - I
        J = np.ones((4, 4))
        G = (2/4) * J - np.eye(4)
        return G

    def create_coin_dft(self):
        """Create the Discrete Fourier Transform coin (4×4)."""
        omega = np.exp(2j * np.pi / 4)
        DFT = np.array([[omega**(k*l) for l in range(4)] for k in range(4)]) / np.sqrt(4)
        return DFT

    def create_coin_hadamard_4d(self):
        """Create the 4D Hadamard coin (tensor product of 2D Hadamards)."""
        H2 = np.array([[1, 1], [1, -1]]) / np.sqrt(2)
        H4 = np.kron(H2, H2)
        return H4

    def create_coin_parameterized(self, params):
        """
        Create a parameterized SU(4) coin using 6 parameters (simplified).

        Parameters: [θ_R, θ_L, θ_U, θ_D, φ_R, φ_L, φ_U, φ_D]
        This creates a diagonal coin with phase shifts.
        """
        theta_R, theta_L, theta_U, theta_D, phi_R, phi_L, phi_U, phi_D = params[:8]

        # Create a biased coin with phases
        # This is a simplified version - full SU(4) requires more parameters
        C = np.array([
            [np.sqrt(theta_R), np.sqrt(theta_L), np.sqrt(theta_U), np.sqrt(theta_D)],
            [np.sqrt(theta_R), -np.sqrt(theta_L), np.sqrt(theta_U), -np.sqrt(theta_D)],
            [np.sqrt(theta_R), np.sqrt(theta_L), -np.sqrt(theta_U), -np.sqrt(theta_D)],
            [np.sqrt(theta_R), -np.sqrt(theta_L), -np.sqrt(theta_U), np.sqrt(theta_D)]
        ])

        # Normalize columns to make unitary (simplified)
        for col in range(4):
            norm = np.sqrt(np.sum(np.abs(C[:, col])**2))
            if norm > 0:
                C[:, col] /= norm

        # Apply phases
        C[0, :] *= np.exp(1j * phi_R)
        C[1, :] *= np.exp(1j * phi_L)
        C[2, :] *= np.exp(1j * phi_U)
        C[3, :] *= np.exp(1j * phi_D)

        return C

    def create_coin_random_su4(self):
        """Create a random SU(4) coin."""
        H = np.random.randn(4, 4) + 1j * np.random.randn(4, 4)
        H = H + H.conj().T  # Make Hermitian
        # Make traceless for SU(4)
        H = H - np.trace(H) / 4 * np.eye(4)
        U = expm(1j * H)
        return U

    def build_evolution_operator(self, coin):
        """
        Build the full evolution operator U = S · (I_N ⊗ C)

        where S is the total shift operator and C is the coin.
        """
        self._build_shift_operators()

        # Total shift operator in coin-position basis
        S_total = np.zeros((self.dim, self.dim), dtype=complex)

        for pos in range(self.N):
            # Right shift
            target_pos = self.right_neighbor[pos]
            S_total[4 * target_pos + self.R, 4 * pos + self.R] = 1

            # Left shift
            target_pos = self.left_neighbor[pos]
            S_total[4 * target_pos + self.L, 4 * pos + self.L] = 1

            # Up shift
            target_pos = self.up_neighbor[pos]
            S_total[4 * target_pos + self.U, 4 * pos + self.U] = 1

            # Down shift
            target_pos = self.down_neighbor[pos]
            S_total[4 * target_pos + self.D, 4 * pos + self.D] = 1

        # Coin operator applied to all positions
        I_N = np.eye(self.N)
        C_total = np.kron(I_N, coin)

        # Full evolution
        U = S_total @ C_total

        return U

    def get_initial_state(self, pos, coin_state):
        """
        Get initial state localized at position with given coin state.

        Parameters:
        - pos: position index (0 to N-1)
        - coin_state: 0=R, 1=L, 2=U, 3=D
        """
        psi = np.zeros(self.dim, dtype=complex)
        psi[4 * pos + coin_state] = 1.0
        return psi

    def get_position_probabilities(self, psi):
        """Compute probability at each position."""
        probs = np.zeros(self.N)
        for pos in range(self.N):
            probs[pos] = np.sum(np.abs(psi[4*pos:4*pos+4])**2)
        return probs

    def check_revival(self, U, N_steps, initial_state, tol=1e-8):
        """
        Check if the walk returns to the initial state after N_steps.

        Returns fidelity and whether revival occurred.
        """
        psi = initial_state.copy()
        for step in range(N_steps):
            psi = U @ psi

        fidelity = np.abs(np.vdot(initial_state, psi))**2
        is_revival = (1 - fidelity) < tol

        return is_revival, fidelity


def search_revivals_non_separable(n, m, max_N=30, num_samples=50):
    """
    Search for revivals in non-separable quantum walks on n×m torus.
    """
    print(f"\n{'=' * 60}")
    print(f"Searching for revivals on {n}×{m} torus")
    print(f"{'=' * 60}")

    walk = NonSeparableQuantumWalk(n, m)

    # Test different coin types
    coin_types = {
        'Grover': walk.create_coin_grover(),
        'DFT': walk.create_coin_dft(),
        'Hadamard_4D': walk.create_coin_hadamard_4d(),
    }

    results = defaultdict(list)

    # Test known coin types
    for coin_name, coin in coin_types.items():
        print(f"\nTesting {coin_name} coin...")
        U = walk.build_evolution_operator(coin)

        # Start from position (0,0) with right-moving coin state
        initial_state = walk.get_initial_state(0, walk.R)

        for N in range(1, max_N + 1):
            is_revival, fidelity = walk.check_revival(U, N, initial_state)
            if is_revival:
                print(f"  ✓ Revival at N={N} (fidelity={fidelity:.10f})")
                results[coin_name].append(N)
            elif fidelity > 0.99:
                print(f"  ~ Near revival at N={N} (fidelity={fidelity:.10f})")

    # Test random parameterized coins
    print(f"\nTesting {num_samples} random parameterized coins...")

    revival_count = 0
    for sample in range(num_samples):
        # Generate random SU(4) coin
        U_coin = walk.create_coin_random_su4()
        U = walk.build_evolution_operator(U_coin)
        initial_state = walk.get_initial_state(0, walk.R)

        for N in range(1, min(max_N, 15)):
            is_revival, fidelity = walk.check_revival(U, N, initial_state)
            if is_revival:
                revival_count += 1
                print(f"  ✓ Random revival: N={N}, sample={sample+1}, fidelity={fidelity:.6f}")
                break

    print(f"\nFound {revival_count} revivals in {num_samples} random coins")

    return results


def visualize_walk(U, walk, n, m, max_steps=16):
    """
    Visualize the probability distribution evolution.
    """
    fig, axes = plt.subplots(2, 3, figsize=(15, 8))
    axes = axes.flatten()

    initial_state = walk.get_initial_state(0, walk.R)

    steps_to_show = [0, 2, 4, 8, 12, max_steps]

    for idx, step in enumerate(steps_to_show):
        if idx >= len(axes):
            break

        # Get state at this step
        if step > 0:
            U_power = np.linalg.matrix_power(U, step)
            psi_step = U_power @ initial_state
        else:
            psi_step = initial_state

        # Get position probabilities
        probs = walk.get_position_probabilities(psi_step)
        prob_grid = probs.reshape(n, m)

        ax = axes[idx]
        im = ax.imshow(prob_grid, cmap='hot', interpolation='bilinear', origin='lower')
        ax.set_title(f'Step {step}')
        ax.set_xlabel('Column (x)')
        ax.set_ylabel('Row (y)')

        # Mark start position
        ax.plot(0, 0, 'wo', markersize=8, markerfacecolor='none', markeredgecolor='white', markeredgewidth=2)

    plt.suptitle(f'Probability Distribution Evolution on {n}×{m} Torus (Grover Coin)\n'
                 f'Initial state: position (0,0), coin: right',
                 fontsize=12)
    plt.colorbar(im, ax=axes, label='Probability')
    plt.tight_layout()
    plt.savefig(f'non_separable_{n}x{m}_grover.png', dpi=150, bbox_inches='tight')
    plt.show()
    print(f"  Saved: non_separable_{n}x{m}_grover.png")


def analyze_coin_spectrum(coin, coin_name):
    """Analyze the eigenvalue spectrum of a coin."""
    evals = np.linalg.eigvals(coin)
    phases = np.angle(evals)
    print(f"\n{coin_name} coin eigenvalues (phases in π):")
    for ev, phase in zip(evals, phases):
        print(f"  λ = {ev.real:.4f} + {ev.imag:.4f}i, phase = {phase/np.pi:.4f}π")


