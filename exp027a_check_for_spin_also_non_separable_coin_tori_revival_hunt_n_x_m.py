    walk = NonSeparableQuantumWalkAnalyzer(2, 2)

    coins = {
        'Grover': walk.create_coin_grover(),
    }

    for coin_name, coin in coins.items():
        print(f"\n{coin_name} Coin:")
        print("-" * 40)

        U = walk.build_evolution_operator(coin)
        results = walk.check_revivals(U, pos=0, max_N=30)

        print(f"  Full state revivals (position + R coin): N = {results['full_state']}")
        print(f"  Position-only revivals (any coin): N = {results['position_only']}")
