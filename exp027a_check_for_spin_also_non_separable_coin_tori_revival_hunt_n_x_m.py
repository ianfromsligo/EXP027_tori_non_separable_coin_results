def visualize_revival_sequence(walk, U, pos, N_revival, save_path=None):
    """
    Visualize the probability distribution at different times
    leading up to and including a revival.
    """
    psi_init = walk.get_initial_state(pos, walk.R)

    times = [0, N_revival//4, N_revival//2, 3*N_revival//4, N_revival]
    times = [t for t in times if t >= 0]

    fig, axes = plt.subplots(1, len(times), figsize=(4*len(times), 4))
    if len(times) == 1:
        axes = [axes]

    for idx, t in enumerate(times):
        if t == 0:
            psi_t = psi_init
        else:
            U_power = np.linalg.matrix_power(U, t)
            psi_t = U_power @ psi_init

        probs = walk.get_position_probabilities(psi_t)
        prob_grid = probs.reshape(walk.n, walk.m)

        ax = axes[idx]
        im = ax.imshow(prob_grid, cmap='hot', interpolation='bilinear', origin='lower')
        ax.set_title(f'Step {t}')
        ax.set_xlabel('Column')
        ax.set_ylabel('Row')

        # Mark start position
        ax.plot(0, 0, 'wo', markersize=10, markerfacecolor='none',
                markeredgecolor='white', markeredgewidth=2)

    plt.suptitle(f'Revival at N={N_revival} on {walk.n}×{walk.m} Torus\n'
                 f'Initial state: position (0,0), coin: right',
                 fontsize=12)
    plt.colorbar(im, ax=axes, label='Probability')
    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches='tight')
        print(f"  Saved: {save_path}")
    plt.show()


