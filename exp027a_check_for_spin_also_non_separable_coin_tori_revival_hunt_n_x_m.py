import numpy as np
from scipy.linalg import expm
import matplotlib.pyplot as plt
from collections import defaultdict


class NonSeparableQuantumWalkAnalyzer:
    """
    Extended version with multiple revival detection methods.
    """

    def __init__(self, n, m):
        self.n = n
        self.m = m
        self.N = n * m
        self.dim = 4 * self.N

        self.R, self.L, self.U, self.D = 0, 1, 2, 3

        self._build_neighbors()

    def _build_neighbors(self):
        self.right_neighbor = np.zeros(self.N, dtype=int)
        self.left_neighbor = np.zeros(self.N, dtype=int)
        self.up_neighbor = np.zeros(self.N, dtype=int)
        self.down_neighbor = np.zeros(self.N, dtype=int)

        for i in range(self.n):
            for j in range(self.m):
                idx = i * self.m + j
                self.right_neighbor[idx] = i * self.m + ((j + 1) % self.m)
                self.left_neighbor[idx] = i * self.m + ((j - 1) % self.m)
                self.up_neighbor[idx] = ((i - 1) % self.n) * self.m + j
                self.down_neighbor[idx] = ((i + 1) % self.n) * self.m + j

    def create_coin_grover(self):
        J = np.ones((4, 4))
        return (2/4) * J - np.eye(4)

    def build_evolution_operator(self, coin):
        # Build shift operator
        S_total = np.zeros((self.dim, self.dim), dtype=complex)

        for pos in range(self.N):
            S_total[4 * self.right_neighbor[pos] + self.R, 4 * pos + self.R] = 1
            S_total[4 * self.left_neighbor[pos] + self.L, 4 * pos + self.L] = 1
            S_total[4 * self.up_neighbor[pos] + self.U, 4 * pos + self.U] = 1
            S_total[4 * self.down_neighbor[pos] + self.D, 4 * pos + self.D] = 1

        I_N = np.eye(self.N)
        C_total = np.kron(I_N, coin)

        return S_total @ C_total

    def get_initial_state(self, pos, coin_state):
        psi = np.zeros(self.dim, dtype=complex)
        psi[4 * pos + coin_state] = 1.0
        return psi

    def get_position_probabilities(self, psi):
        probs = np.zeros(self.N)
        for pos in range(self.N):
            probs[pos] = np.sum(np.abs(psi[4*pos:4*pos+4])**2)
        return probs

    def check_revivals(self, U, pos, max_N, tol=1e-8):
        """
        Check for three types of revivals:
        1. Full state revival (position + exact coin state)
        2. Position revival (any coin state at starting position)
        3. Coin-specific revival (position + specific coin)
        """
        psi_init = self.get_initial_state(pos, self.R)

        results = {
            'full_state': [],
            'position_only': [],
            'coin_R': [],
            'coin_L': [],
            'coin_U': [],
            'coin_D': []
        }

        psi = psi_init.copy()

        for N in range(1, max_N + 1):
            psi = U @ psi

            # 1. Full state revival (exact initial state)
            full_fidelity = np.abs(np.vdot(psi_init, psi))**2
            if full_fidelity > 1 - tol:
                results['full_state'].append(N)

            # 2. Position revival (any coin at start position)
            pos_probs = self.get_position_probabilities(psi)
            if pos_probs[pos] > 1 - tol:
                results['position_only'].append(N)

            # 3. Coin-specific revival at start position
            for coin, name in [(self.R, 'coin_R'), (self.L, 'coin_L'),
                               (self.U, 'coin_U'), (self.D, 'coin_D')]:
                amp = psi[4 * pos + coin]
                prob = np.abs(amp)**2
                if prob > 1 - tol:
                    results[name].append(N)

        return results


def analyze_2x2_revivals():
    """Detailed analysis of 2×2 torus revivals."""
    print("\n" + "=" * 80)
